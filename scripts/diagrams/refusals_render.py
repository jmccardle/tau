"""Turn `refusals.py`'s JSON into `frontend-refusals.md` and `frontend-refusals.dot`.

Every cell is a result `refusals.py` got by making the call; this file only lays
them out.
"""

import json
import sys
from pathlib import Path

COLOURS = {
    "ok": "honeydew",
    "state": "khaki1",  # refused because of what the cursor is doing
    "argument": "gray88",  # refused because the cursor or node is not there
    "dead": "mistyrose",  # refused because the session is closed
}
STATE_REFUSALS = {"Busy", "NotInHook", "WrongFeed"}
ARGUMENT_REFUSALS = {"NoSuchCursor", "NoSuchNode", "NoSuchItem", "NoSuchLabel", "NotPending"}
SHOWN = {"ok (true)": "ok, cancel"}


def kind(cell: str) -> str:
    if cell.startswith("ok"):
        return "ok"
    if cell in STATE_REFUSALS:
        return "state"
    if cell in ARGUMENT_REFUSALS:
        return "argument"
    return "dead"


def esc(text: str) -> str:
    return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def header(label: str) -> str:
    """Break a state's label into short lines."""
    parts = [p.strip() for chunk in label.split(": ") for p in chunk.split(", ")]
    return "<br/>".join(esc(p) for p in parts)


def main(data_path: Path, out: Path) -> None:
    data = json.loads(data_path.read_text())
    states, calls, cells = data["states"], data["calls"], data["cells"]

    def cell(s: dict[str, str], c: dict[str, str]) -> str:
        raw = cells[f"{s['id']}|{c['name']}"]
        return SHOWN.get(raw, raw)

    md = [
        "<!-- Generated by scripts/diagrams.sh. Do not edit. -->",
        "# Frontend calls against cursor states",
        "",
        "Each cell is what the call returned in a fresh session whose cursor was brought to "
        "the state by the public Python API (`scripts/diagrams/refusals.py`). `ok` is "
        "accepted; `ok, cancel` is accepted and the driver must cancel the effect in flight; "
        "anything else is the typed exception.",
        "",
        "| # | state |",
        "|---:|---|",
    ]
    md += [f"| S{i + 1} | {s['label']} |" for i, s in enumerate(states)]
    md += [
        "",
        "| call | " + " | ".join(f"S{i + 1}" for i in range(len(states))) + " |",
        "|---|" + "---|" * len(states),
    ]
    group = ""
    for c in calls:
        if c["group"] != group:
            group = c["group"]
            md.append(f"| **{group}** |" + " |" * len(states))
        md.append(f"| {c['name']} | " + " | ".join(cell(s, c) for s in states) + " |")

    dot = [
        "// Generated by scripts/diagrams.sh. Do not edit.",
        "digraph refusals {",
        '  graph [fontname="Helvetica", labelloc=t, label=<<b>Frontend calls against cursor states'
        "</b><br/>green: accepted. yellow: refused because of what the cursor is doing. "
        "grey: refused because the cursor or node does not exist. "
        "pink: the session is closed>];",
        '  node [shape=plain, fontname="Helvetica", fontsize=9];',
        '  t [label=<<table border="0" cellborder="1" cellspacing="0" cellpadding="3">',
        '<tr><td border="0"></td>'
        + "".join(f'<td bgcolor="gray95"><b>{header(s["label"])}</b></td>' for s in states)
        + "</tr>",
    ]
    group = ""
    for c in calls:
        if c["group"] != group:
            group = c["group"]
            dot.append(
                f'<tr><td align="left" bgcolor="gray85" colspan="{len(states) + 1}">'
                f"<b>{esc(group)}</b></td></tr>"
            )
        row = f'<tr><td align="left">{esc(c["name"])}</td>'
        for s in states:
            text = cell(s, c)
            row += f'<td bgcolor="{COLOURS[kind(text)]}">{esc(text)}</td>'
        dot.append(row + "</tr>")
    dot.append("</table>>];")
    dot.append("}")
    (out / "frontend-refusals.md").write_text("\n".join(md) + "\n")
    (out / "frontend-refusals.dot").write_text("\n".join(dot) + "\n")


if __name__ == "__main__":
    main(Path(sys.argv[1]), Path(sys.argv[2]))
