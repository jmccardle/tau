"""The shape of the core's main types, as the Rust source names them.

Input: the JSON `scripts/diagrams/shapes` (a `syn` program) prints. Output:
`types.dot`. Nothing is added: a box is a struct or enum, a row a field
(`+` public, `-` private) or a variant, and an arrow means a field or variant
names the other type in its own type.
"""

import json
import re
import sys
from pathlib import Path

SHOWN = ["Body", "Node", "Session", "Machine", "Step", "Job", "Answer", "Outcome", "Part"]


def esc(text: str) -> str:
    return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def field_row(f: dict[str, str]) -> str:
    mark = "+" if f["vis"] == "pub" else "-"
    return f"{mark} {f['name']}: {f['ty']}"


def variant_rows(v: dict[str, object]) -> list[str]:
    fields = v["fields"]
    assert isinstance(fields, list)
    if v["shape"] == "unit":
        return [str(v["name"])]
    if v["shape"] == "tuple":
        inner = ", ".join(f["ty"] for f in fields)
        return [f"{v['name']}({inner})"]
    return [f"{v['name']} {{"] + [f"    {f['name']}: {f['ty']}" for f in fields] + ["}"]


def rows(t: dict[str, object]) -> list[str]:
    if t["kind"] == "struct":
        fields = t["fields"]
        assert isinstance(fields, list)
        return [field_row(f) for f in fields]
    out: list[str] = []
    variants = t["variants"]
    assert isinstance(variants, list)
    for v in variants:
        out += variant_rows(v)
    return out


def refs(t: dict[str, object], names: set[str]) -> list[str]:
    """The shown types this one names, in source order, each once."""
    texts: list[str] = []
    if t["kind"] == "struct":
        texts = [f["ty"] for f in t["fields"]]  # type: ignore[attr-defined]
    else:
        for v in t["variants"]:  # type: ignore[attr-defined]
            texts += [f["ty"] for f in v["fields"]]
    out: list[str] = []
    for text in texts:
        for word in re.findall(r"[A-Z]\w*", text):
            if word in names and word not in out and word != t["name"]:
                out.append(word)
    return out


def main(types_json: Path, out: Path) -> None:
    by_name = {t["name"]: t for t in json.loads(types_json.read_text())}
    names = set(SHOWN)
    dot = [
        "// Generated by scripts/diagrams.sh from the Rust source (syn). Do not edit.",
        "digraph types {",
        '  graph [rankdir=LR, fontname="Helvetica", nodesep=0.4, ranksep=1.0, labelloc=t, '
        "label=<<b>Core types, as the source names them</b><br/>"
        "+ public field, - private field; an arrow: the type is named in the other's fields>];",
        '  node [shape=plain, fontname="Helvetica", fontsize=11];',
        '  edge [color="gray40", arrowsize=0.7];',
    ]
    for name in SHOWN:
        t = by_name[name]
        kind = "enum" if t["kind"] == "enum" else "struct"
        body = "".join(
            f'<tr><td align="left" balign="left"><font face="Courier" point-size="10">'
            f"{esc(r).replace(' ', '&nbsp;')}</font></td></tr>"
            for r in rows(t)
        )
        dot.append(
            f'  "{name}" [label=<<table border="1" cellborder="0" cellspacing="0">'
            f'<tr><td bgcolor="lightgray"><b>{name}</b> ({kind}, '
            f"{t['file'].split('/')[-1]})</td></tr>"
            f"{body}</table>>];"
        )
    for name in SHOWN:
        dot += [f'  "{name}" -> "{target}";' for target in refs(by_name[name], names)]
    dot.append("}")
    (out / "types.dot").write_text("\n".join(dot) + "\n")


if __name__ == "__main__":
    main(Path(sys.argv[1]), Path(sys.argv[2]))
