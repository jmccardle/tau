import json
import re
import sys
from collections.abc import Mapping
from pathlib import Path
from typing import Any

from generated import sync

ROOT = Path(__file__).parents[1]
SCHEMA = ROOT / "docs" / "protocol.schema.json"
GUIDE = ROOT / "docs" / "guide" / "protocol.md"
BANNER = "Generated by scripts/protocol_guide.py from docs/protocol.schema.json. Do not edit."

Schema = Any  # a JSON Schema, as json.loads read it
MAX_INLINE = 2  # object types nested deeper than this are shown as `object`
WIRE_NAMES: dict[str, str] = {}  # a Python exception's name -> its error name, set by `guide`

PREAMBLE = """\
# The wire protocol

`tau serve` serves one session over a Unix socket, so a frontend in any language can drive it.
Python programs use [`RemoteClient`](frontends.md#over-the-wire) and need none of this page; it
is for the author of a client in another language. For what the calls mean, read
[the model](model.md) and [writing a frontend](frontends.md): the wire is the `Client` contract,
serialized.

## How it travels

- **Transport.** A WebSocket over the Unix socket `$TAU_HOME/serve/<session id>.sock` (or the
  `--socket` path). The socket's file permissions are the only authentication. `tau serve -d --json`
  prints the socket's path; see [the quickstart](quickstart.md).
- **Messages.** [JSON-RPC 2.0](https://www.jsonrpc.org/specification), one message per WebSocket
  text message. A client sends requests, with parameters by name only (`{"cursor": 0, "text":
  "hi"}`). It sends no batches and no notifications. The server answers each request, and sends
  the notifications `event` and `end`.
- **`hello` comes first.** It names the protocol the client speaks, the client's stable id
  (`john@laptop:vscode`) and, if it wants one, the `buffer` of its event stream. The answer is a
  [Welcome](#welcome). A different protocol number is refused with `ProtocolMismatch` and the
  connection closes: the match is exact. Any other request before `hello`, or a second `hello`,
  is an invalid request and closes the connection.
- **One call per `Client` method.** The method has the `Client` method's name, and a call that
  returns nothing answers `null`. Calls begin in the order they arrive and may finish in any
  order; match a response to its request by `id`. `close` is not a call: close the connection.
- **Events.** The notification `event` has the event's fields as its parameters, plus `kind`, the
  event's name (`{"kind": "CursorView", "cursor": 0, ...}`). The server sends every event a
  response depends on before the response: when `open` answers 3, the `CursorView` of cursor 3
  has already arrived. A client hears `Live` events only for the cursors it `watch`es; every
  other event goes to every client.
- **The end.** The last message is the notification `end`, then the server closes the
  connection. Its `error` is `null` when the server stopped, `CutOff` when the client fell too far
  behind its `buffer`, and `Stopped` when the driver failed.
- **No resume.** A reconnecting client gets a fresh snapshot of events and reads the tree again.
  The log is the truth.

## Reading a value

Two styles share the schema, and both are tagged the way Rust's serde tags them:

- A **node** and what it holds (`Body`, `Part`, `Outcome`, `Author`, `Item`, `Ending`) are
  *externally tagged*: a variant with data is an object with one key, `{"User": "hi"}`, and a
  variant without is a bare string, `"Core"`. This is the encoding of the session's own log.
- An **event** carries its name in `kind`.

Everything else is plain JSON: a dataclass is an object, a tuple an array. Node ids, cursor ids
and item ids are non-negative integers, dense, and never reused. A node never changes once
written, so a client may cache it.

## Errors

A failed call answers a JSON-RPC error object: `code`, `message` (the exception's text) and, for
two codes, `data`. The [table](#error-codes) names every code. `RemoteClient` raises the Python
class in its last column, so a client in another language maps codes to its own errors the same
way.

A call on a server whose driver has stopped or failed answers `Stopped` (-32013).

The descriptions below say which error a call answers by the name in the [table](#error-codes),
which gives its code. Where a value is absent they say `null`.

## The version

`protocol` in `hello` is an integer, now **{protocol}**. It changes only between tagged releases,
when the schema below changed since the last tag. Between releases the wire changes freely: build
a client against the schema of the tau you run, and check `tau serve --schema`.
"""


def wire_words(text: str) -> str:
    """A docstring in the wire's words: the docstrings name Python's exceptions and `None`, which
    a client in another language does not have. An exception becomes the name of the error code
    that `RemoteClient` raises it for, and `None` becomes `null`."""
    text = re.sub(r"\bNone\b", "null", text)
    return re.sub(r"`(\w+)`", lambda m: f"`{WIRE_NAMES.get(m[1], m[1])}`", text)


def one_line(text: object) -> str:
    """A description on one line, safe in a table cell."""
    return " ".join(wire_words(str(text)).split()).replace("|", "\\|")


def anchor(name: str) -> str:
    return name.lower()


def ref_name(ref: str) -> str:
    return ref.rpartition("/")[2]


def ty(s: Schema, depth: int = 0) -> str:
    """The type of a schema, as one line of Markdown."""
    if "$ref" in s:
        name = ref_name(str(s["$ref"]))
        return f"[{name}](#{anchor(name)})"
    choices = [ty(v, depth) for key in ("oneOf", "anyOf") for v in s.get(key, ())]
    if "const" in s:
        choices = [f'`"{s["const"]}"`']
    elif "enum" in s:
        choices = [f"`{json.dumps(v)}`" for v in s["enum"]]
    kind = s.get("type")
    if isinstance(kind, list):
        choices = [f"`{k}`" for k in kind]
    if choices:
        return " or ".join(choices)
    if kind == "array":
        return array_ty(s, depth)
    if kind == "object":
        return object_ty(s, depth)
    return "any JSON value" if kind is None else f"`{kind}`"


def array_ty(s: Schema, depth: int) -> str:
    if "prefixItems" in s:
        inner = ", ".join(ty(v, depth) for v in s["prefixItems"])
        return f"[{inner}]"
    return f"array of {ty(s['items'], depth)}" if "items" in s else "array"


def object_ty(s: Schema, depth: int) -> str:
    """An object with named properties is written out, up to `MAX_INLINE` deep."""
    props: Mapping[str, Schema] = s.get("properties", {})
    if not props or depth >= MAX_INLINE:
        return "`object`"
    required = set(s.get("required", ()))
    parts = [f'`"{n}"`{"" if n in required else "?"}: {ty(p, depth + 1)}' for n, p in props.items()]
    return "{" + ", ".join(parts) + "}"


def properties(s: Schema) -> Mapping[str, Schema]:
    return s.get("properties", {})


def table(s: Schema) -> list[str]:
    """The fields of an object schema as a table (empty list if it has none)."""
    props = properties(s)
    if not props:
        return []
    required = set(s.get("required", ()))
    rows = ["| field | type | notes |", "|---|---|---|"]
    for name, p in props.items():
        note = one_line(p.get("description", "")) if "description" in p else ""
        mark = "" if name in required else "optional"
        rows.append(f"| `{name}` | {ty(p)} | {', '.join(x for x in (mark, note) if x)} |")
    return rows


def describe(s: Schema) -> list[str]:
    return [wire_words(str(s["description"])), ""] if "description" in s else []


def variants(s: Schema) -> list[str]:
    """A `oneOf` as a list, one variant a line, with the description it carries."""
    out: list[str] = []
    for v in s.get("oneOf", ()):
        text = f"- {ty(v)}"
        if "description" in v:
            text += f": {one_line(v['description'])}"
        out.append(text)
        inner = _only_property(v)
        for name, p in properties(inner).items() if inner else ():
            if "description" in p:
                out.append(f"  - `{name}`: {one_line(p['description'])}")
    return [*out, ""]


def _only_property(v: Schema) -> Schema | None:
    """The object inside an externally tagged variant `{"Tag": {...}}`, if there is one."""
    props = properties(v)
    if len(props) == 1:
        (inner,) = props.values()
        return inner if properties(inner) else None
    return None


def value_section(name: str, s: Schema) -> list[str]:
    out = [f"### {name}", "", *describe(s)]
    if "oneOf" in s and all(("enum" in v or "properties" in v) for v in s["oneOf"]):
        out += variants(s)
    elif "oneOf" in s or "anyOf" in s or "enum" in s:
        out += [f"One of: {ty(s)}", ""]
    elif properties(s):
        out += [*table(s), ""]
    else:
        out += [f"{ty(s)}", ""]
    return out


def method_section(name: str, s: Schema) -> list[str]:
    out = [f"### `{name}` method", "", *describe(s)]
    rows = table(s)
    out += ["Parameters:", "", *rows, ""] if rows else ["No parameters.", ""]
    out += [f"Result: {ty(s['x-result'])}", ""]
    return out


def error_section(codes: Schema) -> list[str]:
    out = [
        "## Error codes",
        "",
        *describe(codes),
        "| code | name | `RemoteClient` raises |",
        "|---|---|---|",
    ]
    for code, name, raises in zip(
        codes["enum"],
        codes["x-names"],
        codes["x-raises"],
        strict=True,
    ):
        out.append(f"| {code} | `{name}` | `{raises}` |")
    return [*out, ""]


def event_names(defs: Mapping[str, Schema]) -> list[str]:
    return [ref_name(v["$ref"]) for v in defs["Event"]["oneOf"]]


def wire_names(codes: Schema) -> dict[str, str]:
    """Each Python exception that is raised for exactly one error code, by its error's name, where
    the two differ (`ValueError` is `Refused`)."""
    raised: dict[str, set[str]] = {}
    for name, raises in zip(codes["x-names"], codes["x-raises"], strict=True):
        raised.setdefault(raises, set()).add(name)
    return {
        raises: next(iter(names))
        for raises, names in raised.items()
        if len(names) == 1 and raises not in names
    }


def guide(schema: Schema) -> str:
    defs: Mapping[str, Schema] = schema["$defs"]
    WIRE_NAMES.clear()
    WIRE_NAMES.update(wire_names(defs["ErrorCode"]))
    calls = [n for n, d in defs.items() if "x-result" in d]
    events = event_names(defs)
    deltas = [ref_name(v["$ref"]) for v in properties(defs["Live"])["delta"]["anyOf"]]
    special = {"Event", "ErrorCode", "End", *events, *deltas, *calls}
    values = [n for n in defs if n not in special]
    text = PREAMBLE.replace("{protocol}", str(schema["x-protocol"]))
    out = [f"<!-- {BANNER} -->", "", text, "## Calls", ""]
    out += [
        "Every call of `Client`. `hello` is first; the rest follow in any order.",
        "",
    ]
    for name in ["hello", *(c for c in calls if c != "hello")]:
        out += method_section(name, defs[name])
    out += ["## Events", "", *describe(defs["Event"])]
    for name in events:
        out += value_section(name, defs[name])
    out += ["### Deltas", "", "A `Live` event's `delta` is one of these, tagged by `kind`.", ""]
    for name in deltas:
        out += value_section(name, defs[name])
    out += ["## The end", "", *describe(defs["End"]), *table(defs["End"]), ""]
    out += ["## Values", ""]
    for name in values:
        out += value_section(name, defs[name])
    out += error_section(defs["ErrorCode"])
    return "\n".join(out).rstrip("\n") + "\n"


def generated() -> dict[Path, str]:
    schema = json.loads(SCHEMA.read_text(encoding="utf-8"))
    return {GUIDE: guide(schema)}


def main(args: list[str]) -> int:
    if args not in ([], ["--check"]):
        print("usage: scripts/protocol_guide.py [--check]", file=sys.stderr)
        return 2
    return sync(generated(), check=bool(args), label="protocol guide")


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
