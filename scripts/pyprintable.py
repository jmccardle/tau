"""Generates crates/tau-tokens/src/pyprintable.rs: the characters Python's `repr` escapes.

`repr(str)` prints a character as itself when `str.isprintable` holds for it: the general
category is none of Cc, Cf, Cs, Co, Cn, Zl, Zp or Zs, except U+0020. The table is the sorted
inclusive ranges of the characters that are not printable, taken from the running Python's
`unicodedata`, whose Unicode version it records. The floor Python (3.12, Unicode 15.0) is the
one to generate with.

    scripts/pyprintable.py                  write the file
    scripts/pyprintable.py --check          fail when the file is stale, or was made with another
                                            Unicode version than this Python has
    scripts/pyprintable.py --check --skip-other-version
                                            as --check, but say so and pass when only the
                                            Unicode version differs (check.sh on a newer Python)
"""

import argparse
import sys
import unicodedata
from pathlib import Path

from generated import sync

ROOT = Path(__file__).parents[1]
TARGET = ROOT / "crates/tau-tokens/src/pyprintable.rs"
SPACE = 0x20
BMP = 0xFFFF
NOT_PRINTABLE = {"Cc", "Cf", "Cs", "Co", "Cn", "Zl", "Zp", "Zs"}


def ranges() -> list[tuple[int, int]]:
    """The inclusive ranges of code points `repr` escapes."""
    out: list[tuple[int, int]] = []
    for code in range(0x110000):
        if unicodedata.category(chr(code)) in NOT_PRINTABLE and code != SPACE:
            if out and out[-1][1] == code - 1:
                out[-1] = (out[-1][0], code)
            else:
                out.append((code, code))
    return out


def literal(code: int) -> str:
    """A code point as a Rust hex literal, with the separator clippy wants past four digits."""
    if code > BMP:
        return f"0x{code >> 16:04X}_{code & BMP:04X}"
    return f"0x{code:04X}"


def render() -> str:
    """The Rust source for this Python's Unicode version."""
    table = ranges()
    rows = "".join(f"    ({literal(a)}, {literal(b)}),\n" for a, b in table)
    return (
        "// Generated by `scripts/pyprintable.py`; do not edit. Regenerate with\n"
        "// `.venv/bin/python scripts/pyprintable.py` (the floor Python); `--check` holds it.\n"
        "\n"
        "/// The Unicode version of Python's `unicodedata` this table was made from. Nothing in\n"
        "/// the crate reads it: `tests/tokens/test_repr_printable.py` does, to know what it\n"
        "/// may compare.\n"
        "#[allow(dead_code)]\n"
        f'pub(crate) const UNICODE_VERSION: &str = "{unicodedata.unidata_version}";\n'
        "\n"
        "/// Inclusive ranges of the code points Python's `repr` escapes, sorted.\n"
        f"pub(crate) const NOT_PRINTABLE: [(u32, u32); {len(table)}] = [\n"
        f"{rows}"
        "];\n"
    )


def table_version(text: str) -> str | None:
    """The Unicode version a generated file records."""
    for line in text.splitlines():
        if line.startswith("pub(crate) const UNICODE_VERSION"):
            return line.split('"')[1]
    return None


def main() -> int:
    """Write the table, or with `--check` compare it."""
    parser = argparse.ArgumentParser(description=(__doc__ or "").split("\n")[0])
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--skip-other-version", action="store_true")
    args = parser.parse_args()
    if args.check:
        have = table_version(TARGET.read_text(encoding="utf-8")) if TARGET.exists() else None
        if have != unicodedata.unidata_version:
            message = (
                f"pyprintable: table is Unicode {have}, this Python is "
                f"{unicodedata.unidata_version}; not compared"
            )
            if args.skip_other_version:
                print(message)
                return 0
            print(message, file=sys.stderr)
            return 1
    return sync({TARGET: render()}, check=args.check, label="pyprintable")


if __name__ == "__main__":
    sys.exit(main())
