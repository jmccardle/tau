//! Local tokenizers for τ's token counts (D26 §7): bytes in, counts out.
//!
//! This crate reads no file, opens no connection and reads no clock. A caller hands it the
//! bytes of a `tokenizer.json`, the bytes of a `tokenizer_config.json` or a template's text,
//! a request's messages and tools as JSON, and the time when a template asks for it; it hands
//! back token ids, counts and rendered text. It is built into the second wheel
//! (`ffwf-tau-tokens`, by `tau-tokens-py`); nothing in the main wheel depends on it.
//!
//! - [`Tokenizer`]: an embedded `OpenAI` encoding or a Hugging Face `tokenizer.json`; `encode`
//!   and `count`, where `count` is always the length of `encode` and remembers the pieces it
//!   has counted.
//! - [`ChatTemplate`]: a model's chat template, rendered as `transformers` renders it.
//! - [`TokenizerId`]: the identity strings (`tiktoken:o200k_base`, `hf:OWNER/REPO@REVISION`,
//!   `file:/abs/tokenizer.json`).
//! - [`catalogue`], [`candidates`], [`verdict`]: which tokenizers a model might use, and
//!   whether a server's reported counts agree with one.
//!
//! What "exact" means here: `count(text)` equals the number of ids the same tokenizer files
//! give in the reference implementations (`tokenizers`, `tiktoken`), and a rendering equals
//! `apply_chat_template`'s byte for byte, on everything the tests compare
//! (`tests/fixtures/tokens`, regenerated by `scripts/tokens_goldens.py`). Whether a server
//! bills that count is for its reports to confirm; this crate never labels a count.

